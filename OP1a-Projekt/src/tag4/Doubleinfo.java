package tag4;

// Klasse Double ist eine wrapperklasse für den elementaren Typ double
// فئة Double هي فئة غلاف لنوع البيانات الأساسي double
// Double stellt Informationen für Kommazahlen bereit
//Double يقدّم معلومات للأعداد العشرية
public class Doubleinfo {
    static void main(String[] args) {
        System.out.println("Maximum: " + Double.MAX_VALUE);
        System.out.println("Minimum: " + Double.MIN_VALUE);

        System.out.println(Double.NaN);
    }
}
