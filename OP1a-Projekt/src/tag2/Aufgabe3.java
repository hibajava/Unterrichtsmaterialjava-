package tag2;
/*
Für 6 beliebige ganze Zahlen (z.B. 3 / 11 / 15 / 17 / 33 / 42) soll folgender Text ausgegeben werden:
1.Zahl: 3
2.Zahl: 11
3.Zahl: 15
4.Zahl: 17
5.Zahl: 33
6.Zahl: 42
 */
public class Aufgabe3 {
    static void main(String[] args) {
        System.out.println(1+ ".Zahl: " + 3);
        System.out.println(2+ ".Zahl: " + 11);
        System.out.println(3+ ".Zahl: " + 15);
        System.out.println(4+ ".Zahl: " + 17);
        System.out.println(5+ ".Zahl: " + 33);
        System.out.println(6+ ".Zahl: " + 42);
    }
}
